declare(strict_types=1);

namespace IQ2i\StoriaBundle\Export;

use IQ2i\StoriaBundle\Menu\MenuBuilder;
use IQ2i\StoriaBundle\Url\StaticUrlGenerator;
use IQ2i\StoriaBundle\View\Dto\Variant;
use IQ2i\StoriaBundle\View\ViewBuilder;
use IQ2i\StoriaBundle\View\ViewFinder;
use IQ2i\StoriaBundle\View\ViewRenderer;
use Symfony\Component\Filesystem\Filesystem;
use Symfony\Component\Finder\Finder;

readonly class StaticExporter
{
    public const string MARKER_FILE = '.storia-export';

    public function __construct(
        private ViewFinder $viewFinder,
        private ViewBuilder $viewBuilder,
        private MenuBuilder $menuBuilder,
        private ViewRenderer $viewRenderer,
        private UrlRewriter $urlRewriter,
        private AssetCollector $assetCollector,
        private Filesystem $filesystem,
        private string $bundlePublicDir,
    ) {
    }

    /**
     * @param ?callable(string, string): void $onProgress
     */
    public function export(string $outputDir, ?callable $onProgress = null): ExportResult
    {
        $outputDir = rtrim($outputDir, '/');
        $this->prepareOutputDirectory($outputDir);
        $this->copyBundleAssets($outputDir);

        $variantsByView = $this->findVariants();
        $firstVariants = array_map(static fn (array $variants): ?string => $variants[0] ?? null, $variantsByView);
        $exportedAt = new \DateTimeImmutable();

        $references = [];
        $variantCount = 0;
        foreach ($variantsByView as $path => $variants) {
            foreach ($variants as $variant) {
                try {
                    $references[$path.':'.$variant] = $this->exportVariant($outputDir, $path, $variant, $firstVariants, $exportedAt);
                } catch (\Throwable $e) {
                    throw $e instanceof ExportException ? $e : ExportException::forView($path, $variant, $e);
                }

                ++$variantCount;
                if (null !== $onProgress) {
                    $onProgress($path, $variant);
                }
            }
        }

        $this->writeIndex($outputDir, $firstVariants, $exportedAt);

        try {
            $assetCount = $this->assetCollector->collect($references, $outputDir);
        } catch (ExportException $e) {
            throw $e;
        } catch (\Throwable $e) {
            throw new ExportException(\sprintf('Assets cannot be exported: %s', $e->getMessage()), 0, $e);
        }

        return new ExportResult(\count($variantsByView), $variantCount, $assetCount);
    }

    private function prepareOutputDirectory(string $outputDir): void
    {
        if ('' === $outputDir) {
            throw new ExportException('The output directory cannot be empty.');
        }

        if (is_file($outputDir)) {
            throw new ExportException(\sprintf('The output "%s" is a file, a directory is expected.', $outputDir));
        }

        if (is_dir($outputDir) && [] !== array_diff((array) scandir($outputDir), ['.', '..'])) {
            if (!is_file($outputDir.'/'.self::MARKER_FILE)) {
                throw new ExportException(\sprintf('The output directory "%s" is not empty and was not created by storia:export, refusing to overwrite it. Choose another directory or empty this one.', $outputDir));
            }

            $this->filesystem->remove((new Finder())->in($outputDir)->depth('== 0')->ignoreDotFiles(false));
        }

        $this->filesystem->mkdir($outputDir);
        $this->filesystem->dumpFile($outputDir.'/'.self::MARKER_FILE, "Generated by storia:export, this directory is emptied by the next export.\n");
    }

    private function copyBundleAssets(string $outputDir): void
    {
        $finder = (new Finder())->files()->in($this->bundlePublicDir);
        foreach ($finder as $file) {
            $this->filesystem->copy($file->getPathname(), $outputDir.'/bundles/iq2istoria/'.$file->getRelativePathname(), true);
        }
    }

    /**
     * @return array<string, list<string>>
     */
    private function findVariants(): array
    {
        $variantsByView = [];
        foreach ($this->viewFinder->findPaths() as $path) {
            try {
                $view = $this->viewBuilder->create($path, null);
            } catch (\Throwable $e) {
                throw ExportException::forView($path, null, $e);
            }

            $variants = array_map(static fn (Variant $variant): string => $variant->getPath(), $view?->getVariants() ?? []);
            if ([] === $variants) {
                throw new ExportException(\sprintf('View "%s" defines no variant, there is nothing to export.', $path));
            }

            foreach ($variants as $variant) {
                if (!preg_match('/^[^\/\\\\\0.][^\/\\\\\0]*$/', $variant)) {
                    throw new ExportException(\sprintf('Variant "%s:%s" cannot be exported, its name is not a valid file name.', $path, $variant));
                }
            }

            $variantsByView[$path] = $variants;
        }

        return $variantsByView;
    }

    /**
     * @param array<string, ?string> $firstVariants
     *
     * @return list<string>
     */
    private function exportVariant(string $outputDir, string $path, string $variant, array $firstVariants, \DateTimeImmutable $exportedAt): array
    {
        $view = $this->viewBuilder->create($path, $variant) ?? throw new ExportException(\sprintf('View "%s" disappeared during the export.', $path));

        $file = $path.'/'.$variant.'.html';
        $menu = $this->menuBuilder->createSidebarMenu(new StaticUrlGenerator($file), $path, $firstVariants);
        $this->filesystem->dumpFile(
            $outputDir.'/'.$file,
            $this->viewRenderer->renderShell($view, $menu->getChildren(), new StaticUrlGenerator($file), $exportedAt)
        );

        $iframe = $this->viewRenderer->renderIframe($view);
        $iframeFile = 'iframe/'.$file;
        $this->filesystem->dumpFile($outputDir.'/'.$iframeFile, $this->urlRewriter->rewriteHtml($iframe, UrlRewriter::prefixFor($iframeFile)));

        return $this->urlRewriter->extractHtmlUrls($iframe);
    }

    /**
     * @param array<string, ?string> $firstVariants
     */
    private function writeIndex(string $outputDir, array $firstVariants, \DateTimeImmutable $exportedAt): void
    {
        $urls = new StaticUrlGenerator();
        $menu = $this->menuBuilder->createSidebarMenu($urls, null, $firstVariants);

        $this->filesystem->dumpFile($outputDir.'/index.html', $this->viewRenderer->renderShell(null, $menu->getChildren(), $urls, $exportedAt));
    }
}
